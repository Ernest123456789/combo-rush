"""Анимации гранат: draw (достать), throw (выдернуть чеку, замах, бросок, снова достать следующую), inspect.
Бросок происходит на 0.35 с (7 тиков) — на этом моменте сервер создаёт гранату и граната в руке скрывается."""
from anim import An, ANIMS, Z

HIDE = (0.001, 0.001, 0.001)
ONE = (1, 1, 1)

def _grenade(gid, lever=True, rag=False):
    out = {}
    a = An(gid, 'draw', 0.6)
    a.pos('weapon', [(0, (1, -10, -4)), (0.25, (0.3, -3, -1)), (0.4, (0, 0.8, 0.3)), (0.5, (0, -0.3, 0)), (0.6, Z)])
    a.rot('weapon', [(0, (-55, 20, 14)), (0.25, (-15, 6, 5)), (0.4, (6, -2, -2)), (0.5, (-1.5, 0, 0)), (0.6, Z)])
    out[a.key] = a.d

    a = An(gid, 'throw', 0.9)
    a.pos('weapon', [(0, Z), (0.14, (0, 0.4, -1.2)), (0.24, (0, 1.2, -3.2)), (0.31, (0, 1.6, -3.6)), (0.37, (0, 0.8, 2.5)),
                     (0.4, (0, 0.2, 5)), (0.41, (0, 0.2, 5)), (0.5, (1, -10, -4)), (0.72, (0.3, -3, -1)), (0.85, (0, 0.4, 0)), (0.9, Z)])
    a.rot('weapon', [(0, Z), (0.14, (-8, 0, 0)), (0.24, (-28, -6, 4)), (0.31, (-34, -8, 6)), (0.37, (22, 0, -4)), (0.41, (30, 0, -6)),
                     (0.5, (-55, 20, 14)), (0.72, (-15, 6, 5)), (0.85, (3, -1, -1)), (0.9, Z)])
    a.scl('weapon', [(0, ONE), (0.4, ONE), (0.41, HIDE), (0.49, HIDE), (0.5, ONE)])
    if lever:
        a.scl('pin', [(0, ONE), (0.28, ONE), (0.29, HIDE), (0.5, HIDE), (0.51, ONE)])
        a.pos('pin', [(0, Z), (0.12, Z), (0.2, (-5, 0.6, 0)), (0.24, (-9, -3, 0)), (0.5, (-9, -3, 0)), (0.51, Z)])
        a.rot('lever', [(0, Z), (0.22, Z), (0.28, (0, 0, 35)), (0.4, (0, 0, 55)), (0.5, (0, 0, 55)), (0.51, Z)])
        a.pos('lever', [(0, Z), (0.22, Z), (0.28, (0.4, 0.2, 0)), (0.4, (1.0, 0.4, 0)), (0.5, (1.0, 0.4, 0)), (0.51, Z)])
    if rag:
        a.rot('rag', [(0, Z), (0.24, (0, 0, 0)), (0.31, (0, 0, 14)), (0.37, (0, 0, -20)), (0.5, (0, 0, -6)), (0.6, Z)])
    out[a.key] = a.d

    a = An(gid, 'inspect', 3.2)
    a.pos('weapon', [(0, Z), (0.5, (-1, 1.5, -2.5)), (2.5, (-1, 1.5, -2.5)), (3.0, (0, 0.2, -0.3)), (3.2, Z)])
    a.rot('weapon', [(0, Z), (0.5, (-6, 25, -6)), (1.2, (-12, 150, -6)), (1.9, (-12, 290, 4)), (2.5, (-6, 385, 0)), (3.0, (0, 360, 0)), (3.2, (0, 360, 0))])
    if lever:
        a.rot('lever', [(0, Z), (1.3, Z), (1.45, (0, 0, 10)), (1.65, Z)])
    out[a.key] = a.d
    return out

ANIMS.update({
    'grenade_he': lambda: _grenade('grenade_he'),
    'grenade_flash': lambda: _grenade('grenade_flash'),
    'grenade_smoke': lambda: _grenade('grenade_smoke'),
    'grenade_molotov': lambda: _grenade('grenade_molotov', lever=False, rag=True),
})
