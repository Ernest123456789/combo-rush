ANIMS = {'knife': knife, 'bayonet': bayonet, 'skeleton': skeleton, 'claw': claw, 'gurkha': gurkha}


def anim_file(gid):
    an = ANIMS[gid]()
    for d in an.values():
        for b in d.get('bones', {}).values():
            for kind, ch in b.items():
                items = sorted(ch.items(), key=lambda kv: float(kv[0])); ch.clear(); ch.update(items)
    return {'format_version': '1.8.0', 'animations': an}
