"""Анимации ножей v3 (кости weapon → spin → handle/blade). Рука привязана к weapon, поэтому всё, что крутит spin/blade,
происходит «в пальцах»: подброс, вращение, выброс клинка. Соглашения — как в anim.py:
position +x вправо, +y вверх, +z вперёд; rotation +x — остриё вверх, +y — вправо, +z — крен по часовой."""
from anim import An, Z


def _slashes(gid, out, heavy=1.0):
    L = 0.4 * heavy
    a = An(gid, 'attack', L)
    a.pos('weapon', [(0, Z), (0.08 * heavy, (1, 1, -2)), (0.18 * heavy, (-1, -1, 4)), (L, Z)])
    a.rot('weapon', [(0, Z), (0.08 * heavy, (40, -25, 12)), (0.18 * heavy, (-65, 28, -18)), (L, Z)])
    out[a.key] = a.d
    L2 = 0.42 * heavy
    a = An(gid, 'attack2', L2)
    a.pos('weapon', [(0, Z), (0.08 * heavy, (-1, 1, -2)), (0.2 * heavy, (1.5, -1, 4)), (L2, Z)])
    a.rot('weapon', [(0, Z), (0.08 * heavy, (30, 30, -40)), (0.2 * heavy, (-55, -25, 35)), (L2, Z)])
    out[a.key] = a.d


def _inspect(gid, L=3.6):
    a = An(gid, 'inspect', L)
    s = L / 3.6
    a.pos('weapon', [(0, Z), (0.5 * s, (-1, 0.5, -3)), (2.9 * s, (-1, 0.5, -3)), (3.3 * s, (0, 0, -0.5)), (L, Z)])
    a.rot('weapon', [(0, Z), (0.5 * s, (-10, 20, -10)), (1.1 * s, (10, 50, -20)), (1.7 * s, (10, 50, 160)), (2.2 * s, (0, -30, 360)),
                     (2.6 * s, (-10, -50, 400)), (2.9 * s, (0, -20, 360)), (3.3 * s, (0, 0, 360)), (L, (0, 0, 360))])
    return a


# ------------------------------------------------------------------ стандартный нож: прокрут в ладони
def knife():
    out = {}
    a = An('knife', 'draw', 0.75)
    a.pos('weapon', [(0, (2, -12, -4)), (0.3, (0.5, -4, -1)), (0.5, (0, 1.0, 0.4)), (0.75, Z)])
    a.rot('weapon', [(0, (-70, 30, 30)), (0.3, (-20, 10, 10)), (0.5, (8, -3, -3)), (0.75, Z)])
    a.rot('spin', [(0, Z), (0.18, Z), (0.34, (-200, 0, 0)), (0.5, (-360, 0, 0)), (0.75, (-360, 0, 0))])
    out[a.key] = a.d
    _slashes('knife', out)
    a = _inspect('knife'); out[a.key] = a.d
    return out


