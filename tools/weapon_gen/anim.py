    a.rot('bolt', [(t, Z), (t + 0.12, (0, 0, rot_deg)), (t + 0.62, (0, 0, rot_deg)), (t + 0.74, Z)])
    a.pos('bolt', [(t, Z), (t + 0.12, Z), (t + 0.26, (0, 0, -back)), (t + 0.36, (0, 0, -back)), (t + 0.50, Z)])
    return t + 0.74

