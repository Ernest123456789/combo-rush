# Semantics (calibrated against the viewer, GeckoLib/Blockbench convention):
#   position: +x = shooter's right, +y = up, +z = forward (towards muzzle)
#   rotation: +x = pitch muzzle UP, +y = yaw muzzle to the RIGHT, +z = roll clockwise (seen from behind)
import json

class An:
    def __init__(s, gid, name, length, loop=False):
        s.key = f'animation.{gid}.{name}'
        s.d = {'animation_length': length, 'bones': {}}
        if loop: s.d['loop'] = True
    def k(s, bone, kind, frames):
        """frames: list of (t, [x,y,z])"""
        ch = s.d['bones'].setdefault(bone, {}).setdefault(kind, {})
        for t, v in frames:
            ch[f'{t:.2f}'.rstrip('0').rstrip('.') if False else f'{t:.2f}'] = [round(float(a), 3) for a in v]
        return s
    def pos(s, bone, frames): return s.k(bone, 'position', frames)
    def rot(s, bone, frames): return s.k(bone, 'rotation', frames)
    def scl(s, bone, frames): return s.k(bone, 'scale', frames)

Z = (0, 0, 0)

def bolt_rack(a, bone, t0, back=3.5, hold=0.1, tin=0.12, tout=0.14):
    a.pos(bone, [(t0, Z), (t0 + tin, (0, 0, -back)), (t0 + tin + hold, (0, 0, -back)), (t0 + tin + hold + tout, Z)])

