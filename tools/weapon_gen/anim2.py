def galil_anims():
    d = ak47_anims(); out = {}
    for k, v in d.items():
        v = copy.deepcopy(v); out[k.replace('ak47', 'galil')] = v
    r = out['animation.galil.reload']
    r['animation_length'] = 2.7
    # straight mag: gentler rock
    for t in r['bones']['magazine']['rotation']:
        r['bones']['magazine']['rotation'][t][0] *= 0.55
    out['animation.galil.shoot']['bones']['weapon']['rotation']['0.04'] = [3.0, 0.6, 0.8]
    return out

